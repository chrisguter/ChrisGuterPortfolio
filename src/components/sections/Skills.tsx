/* ---------------------------------------------------------------------------
 * Component
 * -------------------------------------------------------------------------*/

export default function Skills() {
  const { t } = useLocale();
  const { label, heading, intro, hint, groups, nodes } = t.skills;

  /* Colons are legal in a fragment but not worth betting `url(#…)` on. */
  const uid = useId().replace(/:/g, "");
  const map = useMemo(() => buildMap(groups, nodes), [groups, nodes]);

  const [selected, setSelected] = useState<Target | null>(null);
  const [hovered, setHovered] = useState<Target | null>(null);
  const [focused, setFocused] = useState<Target | null>(null);

  /* Pointer beats keyboard beats what is committed: a preview shows the same
     highlight without disturbing the selection, exactly as leaving the element
     restores it. */
  const active = hovered ?? focused ?? selected;
  const lit = useMemo(() => resolve(map, active), [map, active]);

  function toggle(target: Target) {
    setSelected((current) => (current === target ? null : target));
  }

  /* Escape is bound to the document rather than to the map, because Safari does
     not move focus to a button when you click it: after a mouse selection the
     keystroke lands on <body>, and a handler scoped to this subtree would never
     see it. Registered only while something is selected, so it is inert the
     rest of the time. */
  useEffect(() => {
    if (selected === null) return;
    function onKeyDown(event: KeyboardEvent) {
      if (event.key === "Escape") setSelected(null);
    }
    document.addEventListener("keydown", onKeyDown);
    return () => document.removeEventListener("keydown", onKeyDown);
  }, [selected]);

  /* A pointer press focuses the button before it clicks it. Committing on any
     focus would make the click that follows read as a second press and undo
     itself, so only a keyboard focus previews. */
  function previewOnFocus(target: Target) {
    return (event: FocusEvent<HTMLButtonElement>) => {
      if (event.currentTarget.matches(":focus-visible")) setFocused(target);
    };
  }

  const detail = selected;
  const detailNode = detail?.startsWith("node:")
    ? map.byId.get(detail.slice(5))
    : undefined;
  const detailHub = detail?.startsWith("group:")
    ? map.hubs.find((hub) => hub.id === detail.slice(6))
    : undefined;
  const detailTone = detailNode
    ? TONE[detailNode.accent]
    : detailHub
      ? TONE[detailHub.accent]
      : undefined;
  const detailRelated = detailNode
    ? (map.neighbours.get(detailNode.id) ?? [])
        .map((id) => map.byId.get(id))
        .filter((node): node is MapNode => node !== undefined)
    : [];
  const detailMembers = detailHub
    ? (map.clusters.find((cluster) => cluster.hub.id === detailHub.id)?.nodes ?? [])
    : [];

  return (
    <Band
      id="skills"
      index={sectionIndex("skills")}
      label={label}
      heading={heading}
      intro={intro}
    >
      <style>{MAP_CSS}</style>

      <div data-rise>
        <ul className="halo-sk-legend" role="list">
          {map.hubs.map((hub) => {
            const tone = TONE[hub.accent];
            const target: Target = `group:${hub.id}`;
            return (
              <li key={hub.id}>
                <button
                  type="button"
                  className="halo-sk-node"
                  style={{ "--ac": tone.field } as CSSProperties}
                  data-state={stateOf(lit, lit.hubs.has(hub.id))}
                  aria-pressed={selected === target}
                  onClick={() => toggle(target)}
                  onPointerEnter={() => setHovered(target)}
                  onPointerLeave={() => setHovered(null)}
                  onFocus={previewOnFocus(target)}
                  onBlur={() => setFocused(null)}
                >
                  <span className="halo-sk-mark" />
                  {hub.label}
                </button>
              </li>
            );
          })}
        </ul>

        <div className="halo-sk-field">
          {/* Decorative by construction: every line here restates a relation
              that the buttons and the text equivalent below already carry. */}
          <svg
            className="halo-sk-canvas"
            viewBox="0 0 100 100"
            preserveAspectRatio="none"
            aria-hidden="true"
            focusable="false"
          >
            <defs>
              {map.hubs.map((hub) => (
                <radialGradient key={hub.id} id={`${uid}-glow-${hub.id}`}>
                  <stop
                    offset="0%"
                    stopColor={TONE[hub.accent].field}
                    stopOpacity="0.3"
                  />
                  <stop
                    offset="100%"
                    stopColor={TONE[hub.accent].field}
                    stopOpacity="0"
                  />
                </radialGradient>
              ))}
              {/* Cross-group edges only: those are the ones drawn in two
                  colours, so a same-group edge would define a gradient from a
                  hue to itself and never reference it. */}
              {map.edges
                .filter((edge) => edge.cross)
                .map((edge) => (
                  <linearGradient
                    key={edge.id}
                    id={`${uid}-edge-${edge.id}`}
                    gradientUnits="userSpaceOnUse"
                    x1={edge.x1}
                    y1={edge.y1}
                    x2={edge.x2}
                    y2={edge.y2}
                  >
                    <stop offset="0%" stopColor={TONE[edge.accentA].field} />
                    <stop offset="100%" stopColor={TONE[edge.accentB].field} />
                  </linearGradient>
                ))}
            </defs>

            {map.hubs.map((hub) => (
              <ellipse
                key={hub.id}
                className="halo-sk-glow"
                data-state={stateOf(lit, lit.hubs.has(hub.id))}
                cx={hub.x}
                cy={hub.y}
                rx={map.glow.rx}
                ry={map.glow.ry}
                fill={`url(#${uid}-glow-${hub.id})`}
              />
            ))}

            {map.spokes.map((spoke) => (
              <line
                key={spoke.node}
                className="halo-sk-spoke"
                data-state={stateOf(lit, lit.spokes.has(spoke.node))}
                x1={spoke.x1}
                y1={spoke.y1}
                x2={spoke.x2}
                y2={spoke.y2}
                stroke={TONE[spoke.accent].field}
                strokeWidth="1"
                vectorEffect="non-scaling-stroke"
              />
            ))}

            {map.edges.map((edge) => (
              <path
                key={edge.id}
                className="halo-sk-edge"
                data-state={stateOf(lit, lit.edges.has(edge.id))}
                d={edge.d}
                fill="none"
                stroke={
                  edge.cross ? `url(#${uid}-edge-${edge.id})` : TONE[edge.accentA].field
                }
                strokeWidth={edge.cross ? 1.5 : 1}
                strokeDasharray={edge.cross ? undefined : "2 3"}
                strokeLinecap="round"
                vectorEffect="non-scaling-stroke"
              />
            ))}
          </svg>

          {map.clusters.map((cluster) => {
            const tone = TONE[cluster.hub.accent];
            return (
              <div
                key={cluster.hub.id}
                style={
                  {
                    "--ac": tone.field,
                    "--ac-ink": tone.ink,
                    "--ac-line": `color-mix(in oklch, ${tone.field} 45%, transparent)`,
                  } as CSSProperties
                }
              >
                <h3
                  className="halo-sk-hub"
                  data-state={stateOf(lit, lit.hubs.has(cluster.hub.id))}
                  style={{ left: `${cluster.hub.x}%`, top: `${cluster.hub.y}%` }}
                >
                  {cluster.hub.label}
                </h3>

                <ul className="halo-sk-nodes" role="list">
                  {cluster.nodes.map((node) => {
                    const target: Target = `node:${node.id}`;
                    const state = stateOf(lit, lit.nodes.has(node.id));
                    return (
                      <li
                        key={node.id}
                        className="halo-sk-slot"
                        data-state={selected === target ? "sel" : state}
                        style={{ left: `${node.x}%`, top: `${node.y}%` }}
                      >
                        <button
                          type="button"
                          className="halo-sk-node"
                          data-state={state}
                          aria-pressed={selected === target}
                          onClick={() => toggle(target)}
                          onPointerEnter={() => setHovered(target)}
                          onPointerLeave={() => setHovered(null)}
                          onFocus={previewOnFocus(target)}
                          onBlur={() => setFocused(null)}
                        >
                          <span className="halo-sk-mark" />
                          {node.label}
                        </button>
                      </li>
                    );
                  })}
                </ul>
              </div>
            );
          })}
        </div>

        {/* Resting state is the hint, so the guidance occupies the space the
            detail will need rather than a line of its own that goes stale. */}
        <div
          className="halo-sk-detail"
          aria-live="polite"
          style={
            detailTone
              ? ({
                  "--ac-line": `color-mix(in oklch, ${detailTone.field} 55%, transparent)`,
                } as CSSProperties)
              : undefined
          }
        >
          {detailNode ? (
            <>
              <p className="meta" style={{ color: detailTone?.ink }}>
                {detailNode.groupLabel}
              </p>
              <p className="text-lead mt-2 text-cream">{detailNode.label}</p>
              {detailNode.note ? (
                <p className="measure mt-3 text-body text-haze">{detailNode.note}</p>
              ) : null}
              {detailRelated.length > 0 ? (
                <ul className="halo-sk-related" role="list">
                  {detailRelated.map((related) => (
                    <li
                      key={related.id}
                      style={{ "--ac": TONE[related.accent].field } as CSSProperties}
                    >
                      <span className="halo-sk-mark" />
                      {related.label}
                    </li>
                  ))}
                </ul>
              ) : null}
            </>
          ) : detailHub ? (
            <>
              <p className="meta" style={{ color: detailTone?.ink }}>
                {detailHub.label}
              </p>
              <ul className="halo-sk-related" role="list">
                {detailMembers.map((member) => (
                  <li
                    key={member.id}
                    style={{ "--ac": TONE[member.accent].field } as CSSProperties}
                  >
                    <span className="halo-sk-mark" />
                    {member.label}
                  </li>
                ))}
              </ul>
            </>
          ) : (
            <p className="meta">{hint}</p>
          )}
        </div>
      </div>

      {/* The drawing is decorative and the buttons carry only their own names,
          so this is where the map exists as prose: every group, every node, its
          note, and the nodes it meets. It is rendered at every breakpoint, so
          there is no size at which the text equivalent is thinner than the
          picture. */}
      <div className="sr-only">
        <ul role="list">
          {map.clusters.map((cluster) => (
            <li key={cluster.hub.id}>
              {cluster.hub.label}
              <ul role="list">
                {cluster.nodes.map((node) => {
                  const related = (map.neighbours.get(node.id) ?? [])
                    .map((id) => map.byId.get(id))
                    .filter((other): other is MapNode => other !== undefined);
                  return (
                    <li key={node.id}>
                      {node.label}
                      {node.note ? <p>{node.note}</p> : null}
                      {related.length > 0 ? (
                        <ul role="list">
                          {related.map((other) => (
                            <li key={other.id}>
                              {other.label} — {other.groupLabel}
                            </li>
                          ))}
                        </ul>
                      ) : null}
                    </li>
                  );
                })}
              </ul>
            </li>
          ))}
        </ul>
      </div>
    </Band>
  );
}
