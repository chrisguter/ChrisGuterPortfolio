/* ---------------------------------------------------------------------------
 * Deterministic trigonometry
 * -------------------------------------------------------------------------*/

/* ECMAScript does not specify the results of Math.sin and Math.cos beyond
   "implementation-approximated", and the suite runs against Chromium and
   WebKit while the markup is generated by Node. A one-ULP disagreement is
   enough to change a rounded coordinate and produce a hydration mismatch, so
   the angles are evaluated here instead: argument reduction to a quarter turn
   plus a Taylor series in nothing but +, - and *, all of which IEEE-754 does
   pin down exactly. Error is below 1e-9 — six orders of magnitude finer than
   the two decimals that survive rounding. */
const QUARTER = 1.5707963267948966;

function sinQuarter(r: number): number {
  const a = QUARTER * r;
  const s = a * a;
  return (
    a *
    (1 +
      s *
        (-1 / 6 +
          s * (1 / 120 + s * (-1 / 5040 + s * (1 / 362880 + s * (-1 / 39916800))))))
  );
}

function cosQuarter(r: number): number {
  const a = QUARTER * r;
  const s = a * a;
  return (
    1 +
    s * (-1 / 2 + s * (1 / 24 + s * (-1 / 720 + s * (1 / 40320 + s * (-1 / 3628800)))))
  );
}

/** Angles are in turns, so a quarter is 0.25 and the reduction is exact. */
function sinTurns(t: number): number {
  const f = (t - Math.floor(t)) * 4;
  const q = Math.floor(f);
  const r = f - q;
  if (q === 0) return sinQuarter(r);
  if (q === 1) return cosQuarter(r);
  if (q === 2) return -sinQuarter(r);
  return -cosQuarter(r);
}

function cosTurns(t: number): number {
  return sinTurns(t + 0.25);
}

function round(value: number): number {
  return Math.round(value * 100) / 100;
}

