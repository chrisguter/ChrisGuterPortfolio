/* ============================================================================
 * The skills mindmap.
 *
 * Two things shape every decision in this file.
 *
 * 1. The page is prerendered, so the geometry has to come out bit-for-bit
 *    identical in Node and in every browser or hydration fails. That rules out
 *    measuring the DOM, and — see `sinTurns` — it rules out Math.sin/cos too.
 *
 * 2. An SVG <g> cannot hold focus. The nodes are therefore real HTML buttons
 *    laid over the drawing, the drawing itself is decorative, and the same
 *    buttons reflow into a grouped chip list below `md`, where a graph this
 *    dense would be unusable. One set of controls, two presentations, so the
 *    small screen can never fall behind the large one.
 * ========================================================================== */

type Target = `node:${string}` | `group:${string}`;

