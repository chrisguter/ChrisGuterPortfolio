interface Lit {
  on: boolean;
  nodes: Set<string>;
  hubs: Set<string>;
  spokes: Set<string>;
  edges: Set<string>;
}

function resolve(map: SkillMap, target: Target | null): Lit {
  const lit: Lit = {
    on: target !== null,
    nodes: new Set(),
    hubs: new Set(),
    spokes: new Set(),
    edges: new Set(),
  };
  if (!target) return lit;

  if (target.startsWith("group:")) {
    const groupId = target.slice(6);
    lit.hubs.add(groupId);
    for (const cluster of map.clusters) {
      if (cluster.hub.id !== groupId) continue;
      for (const node of cluster.nodes) {
        lit.nodes.add(node.id);
        lit.spokes.add(node.id);
      }
    }
    for (const edge of map.edges) {
      if (lit.nodes.has(edge.a) || lit.nodes.has(edge.b)) lit.edges.add(edge.id);
    }
    return lit;
  }

  const nodeId = target.slice(5);
  const self = map.byId.get(nodeId);
  if (!self) return lit;

  lit.nodes.add(nodeId);
  lit.hubs.add(self.group);
  lit.spokes.add(nodeId);
  for (const other of map.neighbours.get(nodeId) ?? []) lit.nodes.add(other);
  for (const edge of map.edges) {
    if (edge.a === nodeId || edge.b === nodeId) lit.edges.add(edge.id);
  }
  return lit;
}

function stateOf(lit: Lit, isLit: boolean): "rest" | "lit" | "dim" {
  if (!lit.on) return "rest";
  return isLit ? "lit" : "dim";
}

