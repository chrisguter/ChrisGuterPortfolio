/** Everything is laid out in a 0–100 square that the SVG stretches to fill
 *  (`preserveAspectRatio="none"`), which is what lets the same coordinates be
 *  both SVG units and CSS percentages at any container shape. */
const GEOM = {
  /* Rings sized so the whole composition, glow included, clears the edges at
     32 nodes. They were 29/27 and 18/22 when the map held 24: a fan spreads
     wider with more members, and the outermost chips ended up pinned flat
     against the boundary with their glow hanging over it. */
  hubRx: 26,
  hubRy: 24,
  nodeRx: 17,
  nodeRy: 18,
  /** Radius of the soft field painted under a hub. An SVG root clips at its own
   *  viewport, so this can never exceed the hub's distance to the canvas edge:
   *  a larger value does not paint a wider glow, it paints a round one with a
   *  straight bite taken out of it. 26 + 24 = 50 puts the rim exactly on the
   *  edge, where the gradient has already fallen to zero. Enforced below rather
   *  than trusted, so the constraint travels if the ring ever moves. */
  glow: 24,
  /** Turns of arc a group's nodes fan across, centred on the direction away
   *  from the middle. The inward gap it leaves is where the cross-group curves
   *  run. */
  spread: 0.66,
  /** Odd-indexed nodes sit on a tighter ring, so neighbours in the fan are
   *  separated by radius as well as by angle. */
  innerRing: 0.72,
  iterations: 160,
  gapX: 2.2,
  gapY: 1.8,
  /** Fraction of the way from an edge's midpoint to the centre of the canvas
   *  that its control point sits — the pull that turns a chord into a curve. */
  bow: 0.42,
} as const;

/* Chip footprints are estimated from label length against the tightest
   container the graph is ever drawn in (~672 x 480 at the md breakpoint), so
   the separation pass below is always solving the worst case and every wider
   viewport only adds air. Deliberately generous: a label is measured, never
   guessed, only by the browser, and this has to hold for both locales.

   The coefficients are an upper bound on every label in both locales as the
   browser actually draws them, checked at 768 / 1024 / 1440 / 1920. The old
   pair was a fit, not a bound — it under-measured a short all-caps label like
   CPQ by 3px a side, which is precisely the error that ends up on the edge. */
const REF_W = 672;
const REF_H = 480;

function chipBox(label: string): { hx: number; hy: number } {
  return {
    hx: ((38 + label.length * 7.2) / 2 / REF_W) * 100,
    hy: (31 / 2 / REF_H) * 100,
  };
}

function hubBox(label: string): { hx: number; hy: number } {
  return {
    hx: ((26 + label.length * 8.2) / 2 / REF_W) * 100,
    hy: (29 / 2 / REF_H) * 100,
  };
}

/* A node paints well outside its own border box, and none of it is in
   getBoundingClientRect: the selected state's `0 0 34px -6px` shadow reaches
   blur / 2 + spread = 11px past the edge, and `scale(1.06)` then carries the
   whole painting — shadow included — a further 6% of its own half-size
   outward. Fitting the boxes inside the stage therefore fits nothing; the glow
   is what the eye sees against the edge. Twelve, for the eleven plus the
   antialiased tail, reserved in the same reference frame as the footprints. */
const PAINT_PX = 12;
const SELECTED_SCALE = 1.06;
const PAD_X = (PAINT_PX / REF_W) * 100;
const PAD_Y = (PAINT_PX / REF_H) * 100;

interface HubPoint {
  id: string;
  label: string;
  accent: Accent;
  angle: number;
  x: number;
  y: number;
  hx: number;
  hy: number;
}

interface NodePoint {
  node: SkillNode;
  group: HubPoint;
  x: number;
  y: number;
  homeX: number;
  homeY: number;
  hx: number;
  hy: number;
  /** Half-extent of everything the node paints, not of its box. This is what
   *  the canvas edge is measured against. */
  reachX: number;
  reachY: number;
}

interface MapNode {
  id: string;
  label: string;
  note?: string;
  group: string;
  groupLabel: string;
  accent: Accent;
  x: number;
  y: number;
}

interface MapHub {
  id: string;
  label: string;
  accent: Accent;
  x: number;
  y: number;
}

interface MapSpoke {
  node: string;
  group: string;
  accent: Accent;
  x1: number;
  y1: number;
  x2: number;
  y2: number;
}

interface MapEdge {
  id: string;
  a: string;
  b: string;
  cross: boolean;
  accentA: Accent;
  accentB: Accent;
  x1: number;
  y1: number;
  x2: number;
  y2: number;
  d: string;
}

interface SkillMap {
  hubs: MapHub[];
  clusters: { hub: MapHub; nodes: MapNode[] }[];
  byId: Map<string, MapNode>;
  spokes: MapSpoke[];
  edges: MapEdge[];
  neighbours: Map<string, string[]>;
  glow: { rx: number; ry: number };
}

/** Pure: the same content always yields the same map, on the server and in the
 *  browser, with no DOM involved. */
function buildMap(
  groups: readonly SkillGroup[],
  nodes: readonly SkillNode[],
): SkillMap {
  const hubs: HubPoint[] = groups.map((group, index) => {
    /* Start at the top and step clockwise, so the groups appear around the
       canvas in the order they are written in the content file. */
    const angle = 0.75 + index / Math.max(1, groups.length);
    return {
      id: group.id,
      label: group.label,
      accent: group.accent,
      angle,
      x: 50 + GEOM.hubRx * cosTurns(angle),
      y: 50 + GEOM.hubRy * sinTurns(angle),
      ...hubBox(group.label),
    };
  });

  const points: NodePoint[] = [];
  for (const hub of hubs) {
    const members = nodes.filter((node) => node.group === hub.id);
    members.forEach((node, index) => {
      const offset = members.length === 1 ? 0 : index / (members.length - 1) - 0.5;
      const angle = hub.angle + GEOM.spread * offset;
      const ring = index % 2 === 0 ? 1 : GEOM.innerRing;
      const x = hub.x + GEOM.nodeRx * ring * cosTurns(angle);
      const y = hub.y + GEOM.nodeRy * ring * sinTurns(angle);
      const box = chipBox(node.label);
      points.push({
        node,
        group: hub,
        x,
        y,
        homeX: x,
        homeY: y,
        ...box,
        reachX: (box.hx + PAD_X) * SELECTED_SCALE,
        reachY: (box.hy + PAD_Y) * SELECTED_SCALE,
      });
    });
  }

  relax(points, hubs);

  const clusters = hubs.map((hub) => ({
    hub: {
      id: hub.id,
      label: hub.label,
      accent: hub.accent,
      x: round(hub.x),
      y: round(hub.y),
    },
    nodes: points
      .filter((point) => point.group.id === hub.id)
      .map<MapNode>((point) => ({
        id: point.node.id,
        label: point.node.label,
        note: point.node.note,
        group: hub.id,
        groupLabel: hub.label,
        accent: hub.accent,
        x: round(point.x),
        y: round(point.y),
      })),
  }));

  const byId = new Map<string, MapNode>();
  for (const cluster of clusters) {
    for (const node of cluster.nodes) byId.set(node.id, node);
  }

  const spokes: MapSpoke[] = [];
  for (const cluster of clusters) {
    for (const node of cluster.nodes) {
      spokes.push({
        node: node.id,
        group: cluster.hub.id,
        accent: cluster.hub.accent,
        x1: cluster.hub.x,
        y1: cluster.hub.y,
        x2: node.x,
        y2: node.y,
      });
    }
  }

  /* `related` is written from one side only and is not always reciprocated, so
     the pairs are normalised and de-duplicated rather than trusted. An id that
     no longer resolves is dropped: content is edited by hand and a stale
     reference should cost a line, not the section. */
  const edges: MapEdge[] = [];
  const seen = new Set<string>();
  const neighbours = new Map<string, string[]>();

  for (const node of nodes) {
    for (const targetId of node.related ?? []) {
      const from = byId.get(node.id);
      const to = byId.get(targetId);
      if (!from || !to || from.id === to.id) continue;

      const [a, b] = from.id < to.id ? [from, to] : [to, from];
      const id = `${a.id}--${b.id}`;
      if (seen.has(id)) continue;
      seen.add(id);

      neighbours.set(a.id, [...(neighbours.get(a.id) ?? []), b.id]);
      neighbours.set(b.id, [...(neighbours.get(b.id) ?? []), a.id]);

      /* Quadratic, with the control point pulled toward the middle of the
         canvas. The fans leave that middle empty, so the curves bundle through
         it instead of cutting across the labels a straight chord would hit. */
      const midX = (a.x + b.x) / 2;
      const midY = (a.y + b.y) / 2;
      const cx = round(midX + (50 - midX) * GEOM.bow);
      const cy = round(midY + (50 - midY) * GEOM.bow);

      edges.push({
        id,
        a: a.id,
        b: b.id,
        cross: a.group !== b.group,
        accentA: a.accent,
        accentB: b.accent,
        x1: a.x,
        y1: a.y,
        x2: b.x,
        y2: b.y,
        d: `M${a.x} ${a.y}Q${cx} ${cy} ${b.x} ${b.y}`,
      });
    }
  }

  const hubPoints = clusters.map((cluster) => cluster.hub);

  return {
    hubs: hubPoints,
    clusters,
    byId,
    spokes,
    edges,
    neighbours,
    /* Taken from the hub that sits nearest an edge rather than from GEOM alone,
       so the four stay identical and the fit survives a different number of
       groups putting the hubs somewhere other than the four cardinal points. */
    glow: {
      rx: Math.min(GEOM.glow, ...hubPoints.map((hub) => Math.min(hub.x, 100 - hub.x))),
      ry: Math.min(GEOM.glow, ...hubPoints.map((hub) => Math.min(hub.y, 100 - hub.y))),
    },
  };
}

/** Pushes overlapping chips apart while a weak spring holds each one near the
 *  ring position it was born at, so the four fans stay legible as fans. The
 *  forces are continuous — magnitude falls to zero exactly where the boxes stop
 *  touching — which keeps the result stable rather than letting a hair's-width
 *  difference flip a branch and move a node across the canvas. */
function relax(points: NodePoint[], hubs: HubPoint[]): void {
  for (let pass = 0; pass < GEOM.iterations; pass++) {
    for (let i = 0; i < points.length; i++) {
      const a = points[i];
      if (!a) continue;

      for (let j = i + 1; j < points.length; j++) {
        const b = points[j];
        if (!b) continue;
        const dx = b.x - a.x;
        const dy = b.y - a.y;
        const ox = Math.max(0, a.hx + b.hx + GEOM.gapX - Math.abs(dx));
        const oy = Math.max(0, a.hy + b.hy + GEOM.gapY - Math.abs(dy));
        const push = Math.min(ox, oy);
        if (push === 0) continue;

        /* Split across both axes in inverse proportion to how deep the boxes
           are on each, which resolves along the shallower one without the jump
           a hard "pick an axis" test would introduce. */
        const total = ox + oy;
        const mx = ((push * oy) / total) * (dx >= 0 ? 0.5 : -0.5);
        const my = ((push * ox) / total) * (dy >= 0 ? 0.5 : -0.5);
        a.x -= mx;
        a.y -= my;
        b.x += mx;
        b.y += my;
      }

      for (const hub of hubs) {
        const dx = hub.x - a.x;
        const dy = hub.y - a.y;
        const ox = Math.max(0, a.hx + hub.hx + GEOM.gapX - Math.abs(dx));
        const oy = Math.max(0, a.hy + hub.hy + GEOM.gapY - Math.abs(dy));
        const push = Math.min(ox, oy);
        if (push === 0) continue;
        const total = ox + oy;
        a.x -= ((push * oy) / total) * (dx >= 0 ? 1 : -1);
        a.y -= ((push * ox) / total) * (dy >= 0 ? 1 : -1);
      }
    }

    for (const point of points) {
      point.x += (point.homeX - point.x) * 0.03;
      point.y += (point.homeY - point.y) * 0.03;
      /* Against the painted half-extent, not the box. The old bound was the
         box plus a flat 1% of the canvas — under 5px of the short side — so a
         node could satisfy it and still hang its glow over the edge. */
      point.x = Math.min(100 - point.reachX, Math.max(point.reachX, point.x));
      point.y = Math.min(100 - point.reachY, Math.max(point.reachY, point.y));
    }
  }
}

